def banner(text: str) -> None:
    print()
    print("=" * 150)
    print(text)
    print("=" * 150, flush=True)


def norm_text(value: Any) -> str:
    text = re.sub(r"[^a-z0-9]+", " ", str(value).lower())
    return re.sub(r"\s+", " ", text).strip()


def slugify(value: Any) -> str:
    return norm_text(value).replace(" ", "_")


def canonical_ancestry(value: str) -> tuple[str, str]:
    key = norm_text(value)
    if key not in ANCESTRY_ALIASES:
        raise SystemExit(
            f"Unsupported ancestry {value!r}. Use EUR, AFR, EAS, SAS, or AMR."
        )
    return ANCESTRY_ALIASES[key]


def utcnow() -> str:
    return datetime.now(timezone.utc).isoformat()


def clean_str(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, float) and math.isnan(value):
        return ""
    s = str(value).strip()
    if s.lower() in {"nan", "none", "null", "na", "<na>"}:
        return ""
    return s


def truthy(value: Any) -> bool:
    return clean_str(value).lower() in {"1", "true", "yes", "y", "t"}


def finite_float(value: Any) -> float:
    try:
        z = float(value)
    except Exception:
        return np.nan
    return z if math.isfinite(z) else np.nan


def first_numeric(row: pd.Series | dict, names: Iterable[str]) -> float:
    for name in names:
        try:
            value = row.get(name, np.nan)
        except AttributeError:
            value = np.nan
        z = finite_float(value)
        if math.isfinite(z):
            return z
    return np.nan


def first_text(row: pd.Series | dict, names: Iterable[str]) -> str:
    for name in names:
        try:
            value = row.get(name, "")
        except AttributeError:
            value = ""
        s = clean_str(value)
        if s:
            return s
    return ""


def join_unique(values: Iterable[Any], sep: str = ";", limit: int | None = None) -> str:
    seen: list[str] = []
    for value in values:
        s = clean_str(value)
        if not s:
            continue
        tokens = re.split(r"[;,]", s)
        for token in tokens:
            token = token.strip()
            if token and token not in seen:
                seen.append(token)
                if limit is not None and len(seen) >= limit:
                    return sep.join(seen)
    return sep.join(seen)


def safe_write_json(path: Path, obj: dict[str, Any]) -> None:
    def normalise(x: Any) -> Any:
        if isinstance(x, dict):
            return {str(k): normalise(v) for k, v in x.items()}
        if isinstance(x, (list, tuple, set)):
            return [normalise(v) for v in x]
        if isinstance(x, np.integer):
            return int(x)
        if isinstance(x, (np.floating, float)):
            if not math.isfinite(float(x)):
                return None
            return float(x)
        if isinstance(x, np.bool_):
            return bool(x)
        return x

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(normalise(obj), indent=2, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8",
    )


def read_json_compatible(path: Path, retries: int = 3) -> tuple[dict[str, Any], str]:
    last_error = ""
    for attempt in range(retries):
        try:
            if not path.exists() or path.stat().st_size == 0:
                return {}, "MISSING_OR_EMPTY"
            payload = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(payload, dict):
                return payload, "OK"
            return {}, "JSON_ROOT_NOT_OBJECT"
        except Exception as exc:
            last_error = f"{type(exc).__name__}: {exc}"
            if attempt + 1 < retries:
                time.sleep(0.05)
    return {}, last_error or "JSON_READ_FAILED"


def as_numeric_series(df: pd.DataFrame, col: str) -> pd.Series:
    if col not in df.columns:
        return pd.Series(np.nan, index=df.index, dtype=float)
    return pd.to_numeric(df[col], errors="coerce")


def bool_series(df: pd.DataFrame, col: str) -> pd.Series:
    if col not in df.columns:
        return pd.Series(False, index=df.index, dtype=bool)
    return df[col].map(truthy).fillna(False).astype(bool)


def canonical_ensg(text: Any) -> str:
    m = re.search(r"(ENSG\d+)", clean_str(text), flags=re.I)
    return m.group(1).upper() if m else ""


def canonical_enst(text: Any) -> str:
    m = re.search(r"(ENST\d+)", clean_str(text), flags=re.I)
    return m.group(1).upper() if m else ""


def canonical_ensp(text: Any) -> str:
    m = re.search(r"(ENSP\d+)", clean_str(text), flags=re.I)
    return m.group(1).upper() if m else ""


def all_ensg(text: Any) -> list[str]:
    return list(dict.fromkeys(x.upper() for x in re.findall(r"ENSG\d+", clean_str(text), flags=re.I)))


def variant_key(chrom: Any, pos: Any, ref: Any, alt: Any) -> str:
    c = clean_str(chrom)
    c = re.sub(r"^chr", "", c, flags=re.I)
    p = clean_str(pos)
    r = clean_str(ref).upper()
    a = clean_str(alt).upper()
    if not c or not p or not r or not a:
        return ""
    try:
        p = str(int(float(p)))
    except Exception:
        return ""
    return f"{c}:{p}:{r}:{a}"


def normalize_variant_string(value: Any) -> str:
    s = clean_str(value)
    if not s:
        return ""
    s = re.sub(r"^chr", "", s, flags=re.I)
    parts = s.split(":")
    if len(parts) >= 4:
        return variant_key(parts[0], parts[1], parts[2], parts[3])
    return s


def add_variant_key_flexible(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()

    if "VARIANT_KEY" in out.columns:
        existing = out["VARIANT_KEY"].fillna("").astype(str).map(normalize_variant_string)
    else:
        existing = pd.Series("", index=out.index, dtype=str)

    candidates = [
        ("CHR", "REFERENCE_POS", "REFERENCE_REF", "REFERENCE_ALT"),
        ("CHR", "POS", "REF", "ALT"),
        ("CHROM", "POS", "REF", "ALT"),
    ]

    built = pd.Series("", index=out.index, dtype=str)
    for c, p, r, a in candidates:
        if all(x in out.columns for x in [c, p, r, a]):
            built = pd.Series(
                [variant_key(cc, pp, rr, aa) for cc, pp, rr, aa in zip(out[c], out[p], out[r], out[a])],
                index=out.index,
                dtype=str,
            )
            break

    if "REFERENCE_ID" in out.columns:
        refid = out["REFERENCE_ID"].fillna("").astype(str).map(normalize_variant_string)
    else:
        refid = pd.Series("", index=out.index, dtype=str)

    final = existing.copy()
    final = final.where(final.str.len().gt(0), built)
    final = final.where(final.str.len().gt(0), refid)
    out["VARIANT_KEY"] = final
    return out


def print_frame(title: str, df: pd.DataFrame, columns: list[str], n: int = 30) -> None:
    banner(title)
    if df.empty:
        print("No rows.")
        return
    cols = [c for c in columns if c in df.columns]
    if not cols:
        print(f"Rows: {len(df):,}")
        return
    with pd.option_context(
        "display.max_rows", n,
        "display.max_columns", None,
        "display.width", 260,
        "display.max_colwidth", 40,
    ):
        print(df[cols].head(n).to_string(index=False))


