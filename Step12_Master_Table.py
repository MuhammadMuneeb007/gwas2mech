    if len(coverage):
        pending = coverage[coverage["COLOC_LOCUS_STATE"].isin(["FAILED", "PENDING"])]
        print("Coloc loci                  : " + ", ".join(f"{k} {v}" for k, v in summary["COLOC_LOCI"].items()))
