def merge_step06_and_annotations(step06: pd.DataFrame, annot: pd.DataFrame) -> pd.DataFrame:
    if step06.empty and annot.empty:
        return pd.DataFrame()
    if step06.empty:
        return annot.copy()
    if annot.empty:
        return step06.copy()

    s = step06.copy()
    a = annot.copy()
    keys = ["STUDY_ACCESSION", "LOCUS_ID", "VARIANT_KEY"]

    if not all(k in s.columns for k in keys) or not all(k in a.columns for k in keys):
        print("[WARN] Could not merge Step06+annotation on study/locus/variant; using Step06 primary table.")
        return s

    annotation_only = [c for c in a.columns if c not in s.columns or c in keys]
    a2 = a[annotation_only].copy()
    out = s.merge(a2, on=keys, how="left", validate="one_to_one")
    return out


