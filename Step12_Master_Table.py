def add_coloc_flags_to_variants(variants: pd.DataFrame, long: pd.DataFrame) -> pd.DataFrame:
    if variants.empty:
        return variants

    out = variants.copy()
    defaults = {
        "COLOC_IS_GWAS_SIGNAL_HIT": "NO",
        "COLOC_IS_QTL_SIGNAL_HIT": "NO",
        "COLOC_MAX_H4_AS_GWAS_HIT": np.nan,
        "COLOC_MAX_H4_AS_QTL_HIT": np.nan,
        "COLOC_N_STRONG_AS_GWAS_HIT": 0,
        "COLOC_N_STRONG_AS_QTL_HIT": 0,
        "COLOC_EVIDENCE_SOURCES": "",
        "COLOC_CONTEXTS": "",
        "COLOC_EFFECTORS": "",
    }
    for k, v in defaults.items():
        out[k] = v

    if long.empty:
        return out

    tested = long[
        long["FORMAL_COLOC_TESTED"].eq("YES")
        & pd.to_numeric(long["PP_H4"], errors="coerce").notna()
    ].copy()
    if tested.empty:
        return out

    role_rows: list[dict[str, Any]] = []
    for _, r in tested.iterrows():
        base = {
            "STUDY_ACCESSION": clean_str(r.get("STUDY_ACCESSION")),
            "LOCUS_ID": clean_str(r.get("LOCUS_ID")),
            "PP_H4": finite_float(r.get("PP_H4")),
            "IS_STRONG": truthy(r.get("IS_STRONG")),
            "EVIDENCE_SOURCE": clean_str(r.get("EVIDENCE_SOURCE")),
            "CONTEXT_NAME": clean_str(r.get("CONTEXT_NAME")),
            "EFFECTOR_KEY": first_text(r, ["EFFECTOR_GENE_ID", "EFFECTOR_GENE_SYMBOL", "MOLECULAR_TRAIT_ID"]),
        }
        gv = normalize_variant_string(r.get("BEST_GWAS_VARIANT_STEP12", ""))
        qv = normalize_variant_string(r.get("BEST_QTL_VARIANT_STEP12", ""))
        if gv:
            role_rows.append({**base, "VARIANT_KEY": gv, "ROLE": "GWAS"})
        if qv:
            role_rows.append({**base, "VARIANT_KEY": qv, "ROLE": "QTL"})

    if not role_rows:
        return out

    rr = pd.DataFrame(role_rows)
    summaries: list[dict[str, Any]] = []
    for (study, locus, vk), g in rr.groupby(["STUDY_ACCESSION", "LOCUS_ID", "VARIANT_KEY"], sort=True):
        gwas = g[g["ROLE"].eq("GWAS")]
        qtl = g[g["ROLE"].eq("QTL")]
        summaries.append({
            "STUDY_ACCESSION": study,
            "LOCUS_ID": locus,
            "VARIANT_KEY": vk,
            "COLOC_IS_GWAS_SIGNAL_HIT_X": "YES" if len(gwas) else "NO",
            "COLOC_IS_QTL_SIGNAL_HIT_X": "YES" if len(qtl) else "NO",
            "COLOC_MAX_H4_AS_GWAS_HIT_X": pd.to_numeric(gwas["PP_H4"], errors="coerce").max() if len(gwas) else np.nan,
            "COLOC_MAX_H4_AS_QTL_HIT_X": pd.to_numeric(qtl["PP_H4"], errors="coerce").max() if len(qtl) else np.nan,
            "COLOC_N_STRONG_AS_GWAS_HIT_X": int(gwas["IS_STRONG"].astype(bool).sum()) if len(gwas) else 0,
            "COLOC_N_STRONG_AS_QTL_HIT_X": int(qtl["IS_STRONG"].astype(bool).sum()) if len(qtl) else 0,
            "COLOC_EVIDENCE_SOURCES_X": join_unique(g["EVIDENCE_SOURCE"], limit=20),
            "COLOC_CONTEXTS_X": join_unique(g["CONTEXT_NAME"], limit=100),
            "COLOC_EFFECTORS_X": join_unique(g["EFFECTOR_KEY"], limit=100),
        })

    s = pd.DataFrame(summaries)
    out = out.merge(
        s,
        on=["STUDY_ACCESSION", "LOCUS_ID", "VARIANT_KEY"],
        how="left",
        validate="many_to_one",
    )

    for c in list(defaults):
        xc = c + "_X"
        if xc not in out.columns:
            continue
        if isinstance(defaults[c], str):
            out[c] = out[xc].fillna(out[c])
        else:
            out[c] = pd.to_numeric(out[xc], errors="coerce").combine_first(
                pd.to_numeric(out[c], errors="coerce")
            )
        out = out.drop(columns=[xc])

    return out


