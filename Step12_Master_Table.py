def posterior_source(payload: dict[str, Any]) -> str:
    if any(math.isfinite(finite_float(payload.get(f"BEST_PAIR_PP_H{i}"))) for i in range(5)):
        return "BEST_PAIR_PP_H*"
    if any(math.isfinite(finite_float(payload.get(f"BEST_PP_H{i}"))) for i in range(5)):
        return "BEST_PP_H*"
    if any(math.isfinite(finite_float(payload.get(f"MAX_PP_H{i}"))) for i in range(5)):
        return "LEGACY_MAX_PP_H*_FALLBACK"
    return ""


def derive_result_state(status: str, json_state: str, result_present: bool) -> str:
    s = clean_str(status).upper()
    if not result_present:
        return "MISSING"
    if json_state != "OK":
        return "PARSE_ERROR"
    if s == "COMPLETE":
        return "COMPLETE"
    if s.startswith("NOT_TESTED"):
        return "NOT_TESTED"
    if s.startswith("FAILED"):
        return "FAILED"
    if s.startswith("STALE"):
        return "STALE"
    if s in {"", "UNKNOWN"}:
        return "UNKNOWN"
    return s


def derive_evidence_class(
    tested: bool,
    h: list[float],
    strong: float,
    suggestive: float,
    status: str,
) -> str:
    h4 = h[4]
    if not tested:
        s = clean_str(status).upper()
        if s.startswith("NOT_TESTED"):
            return s
        return "NOT_FORMALLY_TESTED"
    if not math.isfinite(h4):
        return "TESTED_NO_FINITE_H4"
    if h4 >= strong:
        return "STRONG_SHARED_SIGNAL"
    if h4 >= suggestive:
        return "SUGGESTIVE_SHARED_SIGNAL"
    finite = [(i, v) for i, v in enumerate(h) if math.isfinite(v)]
    if finite:
        best_h, _ = max(finite, key=lambda kv: kv[1])
        if best_h == 3:
            return "BOTH_ASSOCIATED_DIFFERENT_SIGNALS_FAVORED"
        if best_h == 4:
            return "H4_DOMINANT_BELOW_SUGGESTIVE_THRESHOLD"
        return f"H{best_h}_DOMINANT"
    return "TESTED_NO_FINITE_POSTERIOR"


def extract_best_hits(payload: dict[str, Any]) -> tuple[str, str, str]:
    h1 = first_text(payload, ["BEST_GWAS_VARIANT", "BEST_HIT1", "BEST_GWAS_HIT"])
    h2 = first_text(payload, ["BEST_QTL_VARIANT", "BEST_HIT2", "BEST_QTL_HIT"])
    pair = first_text(payload, ["BEST_SIGNAL_PAIR"])
    if pair and "|" in pair:
        a, b = pair.split("|", 1)
        h1 = h1 or a.strip()
        h2 = h2 or b.strip()
    if not pair and (h1 or h2):
        pair = f"{h1}|{h2}".strip("|")
    return normalize_variant_string(h1), normalize_variant_string(h2), pair


def coloc_result_rows(base: Path) -> tuple[list[dict[str, Any]], int]:
    """Candidate rows of every locus_coloc_results.tsv (EXCLUDED_* = provider credible-set filter, dropped
    like before: they were never coloc candidates). Returns (rows, n_excluded)."""
    rows: list[dict[str, Any]] = []
    n_excluded = 0
    for f in sorted(base.glob("GCST*/loci/L*/locus_coloc_results.tsv")):
        if PIPELINE["study"] and f.parts[-4] != PIPELINE["study"]:
            continue
        try:
            x = pd.read_csv(f, sep="\t", dtype=str, keep_default_na=False, low_memory=False)
        except Exception as exc:
            print(f"[WARN] unreadable {f}: {type(exc).__name__}: {exc}")
            continue
        for r in x.to_dict(orient="records"):
            status = clean_str(r.get("STATUS"))
            if status.startswith("EXCLUDED"):
                n_excluded += 1
                continue
            r["STATUS"] = "COMPLETE" if status == "TESTED" else status
            for i in range(5):
                r[f"BEST_PAIR_PP_H{i}"] = r.get(f"PP_H{i}", "")
            r["PP_H4_P12_DEFAULT"] = r.get("PP_H4", "")
            r["N_GWAS_SIGNALS_USED"] = r.get("N_GWAS_SIGNALS", "")
            r["N_QTL_SIGNALS_USED"] = r.get("N_QTL_SIGNALS", "")
            r["RESULT_FILE"] = str(f)
            rows.append(r)
    return rows, n_excluded


def coloc_locus_coverage(s06: Path, base: Path, evidence_source: str) -> pd.DataFrame:
    """One row per Step06 locus: was it colocalised by this source (done / failed / pending)?"""
    rows = []
    for study_dir in sorted(d for d in s06.glob("GCST*") if d.is_dir()):
        if PIPELINE["study"] and study_dir.name != PIPELINE["study"]:
            continue
        for locus_dir in sorted(study_dir.glob("loci/L*")):
            if not (locus_dir / "susie" / "susie_fit.rds").exists():
                continue
            out = base / study_dir.name / "loci" / locus_dir.name
            done, _ = read_json_compatible(out / "provider_coloc_done.json")
            if not done:
                done, _ = read_json_compatible(out / "custom_coloc_done.json")      # Step11
            state = (clean_str(done.get("STATUS")) or "DONE") if done else (
                "FAILED" if (out / "LOCUS_FAILED.txt").exists() else "PENDING")
            rows.append({"EVIDENCE_SOURCE": evidence_source, "STUDY_ACCESSION": study_dir.name,
                         "LOCUS_ID": locus_dir.name, "COLOC_LOCUS_STATE": state,
                         "N_CANDIDATES": done.get("N_CANDIDATES", "") if done else "",
                         "N_TESTED": done.get("N_TESTED", "") if done else "",
                         "N_CONTEXTS_READY": done.get("N_CONTEXTS_READY", "") if done else ""})
    return pd.DataFrame(rows)


def load_coloc_long(
    base: Path,
    phenotype: str,
    ancestry_code: str,
    ancestry_label: str,
    strong: float,
    suggestive: float,
    evidence_source: str,
    context_level: str,
    required_source: bool,
) -> pd.DataFrame:
    result_rows, n_excluded = coloc_result_rows(base)
    if not result_rows:
        if required_source:
            raise SystemExit(
                f"{evidence_source}: no colocalisation results under {base}\n"
                "Run that step first (planner + sbatch), then check it with --status."
            )
        banner(f"STEP12 - {evidence_source} NOT AVAILABLE")
        print(f"No locus_coloc_results.tsv under {base}")
        return pd.DataFrame()

    banner(f"STEP12 - LOADING {evidence_source}")
    print(f"Results         : {base}")
    print(f"Candidates      : {len(result_rows):,} (+ {n_excluded:,} excluded by the provider credible-set filter)")
    print(f"Context level   : {context_level}")

    rows: list[dict[str, Any]] = []

    for i, mrow in enumerate(result_rows, start=1):
        payload = dict(mrow)
        present, json_state = True, "OK"
        result_file = mrow.get("RESULT_FILE", "")

        row: dict[str, Any] = dict(mrow)

        status = first_text(row, ["STATUS"]) or "UNKNOWN"
        tested = truthy(row.get("COLOC_TESTED", ""))

        source = posterior_source(payload)
        hvals: list[float] = []
        for h in range(5):
            if source == "BEST_PAIR_PP_H*":
                z = finite_float(payload.get(f"BEST_PAIR_PP_H{h}"))
            elif source == "BEST_PP_H*":
                z = finite_float(payload.get(f"BEST_PP_H{h}"))
            elif source == "LEGACY_MAX_PP_H*_FALLBACK":
                z = finite_float(payload.get(f"MAX_PP_H{h}"))
            else:
                z = np.nan
            hvals.append(z)
        if not tested and status.upper() == "COMPLETE" and math.isfinite(hvals[4]):
            tested = True

        low = first_numeric(row, ["PP_H4_P12_LOW", "H4_P12_LOW"])
        default = first_numeric(row, ["PP_H4_P12_DEFAULT", "H4_P12_DEFAULT"])
        if not math.isfinite(default):
            default = hvals[4]
        high = first_numeric(row, ["PP_H4_P12_HIGH", "H4_P12_HIGH"])
        sens = [z for z in [low, default, high] if math.isfinite(z)]

        prior_min = first_numeric(row, ["PRIOR_H4_MIN"])
        prior_max = first_numeric(row, ["PRIOR_H4_MAX"])
        if not math.isfinite(prior_min) and sens:
            prior_min = min(sens)
        if not math.isfinite(prior_max) and sens:
            prior_max = max(sens)

        prior_robust_strong = truthy(row.get("PRIOR_ROBUST_STRONG", ""))
        if sens and min(sens) >= strong:
            prior_robust_strong = True

        prior_robust_suggestive = truthy(row.get("PRIOR_ROBUST_SUGGESTIVE", ""))
        if sens and min(sens) >= suggestive:
            prior_robust_suggestive = True

        hit1, hit2, pair = extract_best_hits(row)

        gene_id = canonical_ensg(first_text(row, ["GENE_ID", "MOLECULAR_TRAIT_ID"]))
        transcript_id = canonical_enst(first_text(row, ["TRANSCRIPT_ID", "MOLECULAR_TRAIT_ID"]))
        protein_id = canonical_ensp(first_text(row, ["PROTEIN_ID", "MOLECULAR_TRAIT_ID"]))

        if gene_id:
            entity_type = "GENE"
        elif transcript_id:
            entity_type = "TRANSCRIPT"
        elif protein_id:
            entity_type = "PROTEIN"
        else:
            qtype = clean_str(row.get("QTL_TYPE")).lower()
            entity_type = {
                "isoqtl": "ISOFORM_OR_TRANSCRIPT",
                "exonqtl": "EXON",
                "sqtl": "SPLICING_PHENOTYPE",
                "pqtl": "PROTEIN_OR_PQTL_TRAIT",
                "eqtl": "GENE_EXPRESSION_TRAIT",
            }.get(qtype, "MOLECULAR_TRAIT")

        tissue = first_text(row, ["TISSUE", "TISSUE_LABEL"])
        condition = first_text(row, ["CONDITION", "CONDITION_LABEL", "CELL_CONDITION"])

        if context_level == "CELL_TYPE":
            cell_type = tissue
            bulk_tissue = ""
            context_name = cell_type
        else:
            cell_type = ""
            bulk_tissue = tissue
            context_name = bulk_tissue

        row.update({
            "STEP12_VERSION": VERSION,
            "PHENOTYPE": phenotype,
            "ANCESTRY_CODE": ancestry_code,
            "ANCESTRY_LABEL": ancestry_label,
            "EVIDENCE_SOURCE": evidence_source,
            "CONTEXT_LEVEL": context_level,
            "CONTEXT_NAME": context_name,
            "BULK_TISSUE": bulk_tissue,
            "CELL_TYPE": cell_type,
            "CONDITION_STEP12": condition,
            "RESULT_FILE": str(result_file),
            "RESULT_PRESENT": "YES" if present else "NO",
            "RESULT_JSON_STATE": json_state,
            "RESULT_STATE": derive_result_state(status, json_state, present),
            "STATUS": status,
            "FORMAL_COLOC_TESTED": "YES" if tested else "NO",
            "POSTERIOR_SOURCE": source,
            "PP_H0": hvals[0],
            "PP_H1": hvals[1],
            "PP_H2": hvals[2],
            "PP_H3": hvals[3],
            "PP_H4": hvals[4],
            "PP_H4_P12_LOW_STEP12": low,
            "PP_H4_P12_DEFAULT_STEP12": default,
            "PP_H4_P12_HIGH_STEP12": high,
            "PRIOR_H4_MIN_STEP12": prior_min,
            "PRIOR_H4_MAX_STEP12": prior_max,
            "PRIOR_ROBUST_STRONG_STEP12": "YES" if prior_robust_strong else "NO",
            "PRIOR_ROBUST_SUGGESTIVE_STEP12": "YES" if prior_robust_suggestive else "NO",
            "EVIDENCE_CLASS_STEP12": derive_evidence_class(
                tested, hvals, strong, suggestive, status
            ),
            "BEST_HIT1_STEP12": hit1,
            "BEST_HIT2_STEP12": hit2,
            "BEST_GWAS_VARIANT_STEP12": hit1,
            "BEST_QTL_VARIANT_STEP12": hit2,
            "BEST_SIGNAL_PAIR_STEP12": pair,
            "EFFECTOR_GENE_ID": gene_id,
            "EFFECTOR_TRANSCRIPT_ID": transcript_id,
            "EFFECTOR_PROTEIN_ID": protein_id,
            "MOLECULAR_ENTITY_TYPE": entity_type,
            "DISCOVERY_MIN_P_STEP12": first_numeric(row, ["DISCOVERY_MIN_P"]),
            "N_COMMON_VARIANTS_STEP12": first_numeric(row, ["N_COMMON_VARIANTS"]),
            "N_GWAS_SIGNALS_USED_STEP12": first_numeric(row, ["N_GWAS_SIGNALS_USED"]),
            "N_QTL_SIGNALS_USED_STEP12": first_numeric(row, ["N_QTL_SIGNALS_USED"]),
        })
        rows.append(row)

        if i % 5000 == 0 or i == len(result_rows):
            print(f"  parsed {i:,}/{len(result_rows):,}", flush=True)

    x = pd.DataFrame(rows)
    if x.empty:
        return x

    x["PP_H4"] = pd.to_numeric(x["PP_H4"], errors="coerce")
    x["IS_STRONG"] = x["FORMAL_COLOC_TESTED"].eq("YES") & x["PP_H4"].ge(strong)
    x["IS_SUGGESTIVE"] = (
        x["FORMAL_COLOC_TESTED"].eq("YES")
        & x["PP_H4"].ge(suggestive)
        & x["PP_H4"].lt(strong)
    )
    x["IS_SHARED_SIGNAL"] = (
        x["FORMAL_COLOC_TESTED"].eq("YES") & x["PP_H4"].ge(suggestive)
    )
    return x


