def build_pathway_input(gene_master: pd.DataFrame, suggestive: float) -> pd.DataFrame:
    if gene_master.empty:
        return pd.DataFrame()

    g = gene_master.copy()
    g["BEST_H4"] = pd.to_numeric(g["BEST_H4"], errors="coerce")
    g = g[g["EFFECTOR_GENE_ID"].astype(str).str.startswith("ENSG")].copy()
    if g.empty:
        return pd.DataFrame()

    rows: list[dict[str, Any]] = []
    for gene, z in g.groupby("EFFECTOR_GENE_ID", sort=True):
        h = pd.to_numeric(z["BEST_H4"], errors="coerce")
        best = z.loc[h.idxmax()] if h.notna().any() else z.iloc[0]
        rows.append({
            "GENE_ID": gene,
            "GENE_SYMBOL": join_unique(z.get("EFFECTOR_GENE_SYMBOL", pd.Series(dtype=str)), limit=20),
            "MAX_H4": float(h.max()) if h.notna().any() else np.nan,
            "N_STUDY_LOCUS_ROWS": int(len(z)),
            "N_STRONG_ROWS": int(h.ge(DEFAULT_STRONG_PP4).sum()),
            "N_SHARED_ROWS": int(h.ge(suggestive).sum()),
            "BEST_STUDY_ACCESSION": clean_str(best.get("STUDY_ACCESSION")),
            "BEST_LOCUS_ID": clean_str(best.get("LOCUS_ID")),
            "BEST_EVIDENCE_SOURCE": clean_str(best.get("BEST_EVIDENCE_SOURCE")),
            "BEST_CONTEXT": clean_str(best.get("BEST_CONTEXT")),
            "BULK_BEST_H4": pd.to_numeric(z.get("BULK_BEST_H4", pd.Series(np.nan, index=z.index)), errors="coerce").max(),
            "CELL_BEST_H4": pd.to_numeric(z.get("CELL_BEST_H4", pd.Series(np.nan, index=z.index)), errors="coerce").max(),
            "IN_EXPANDED_SUGGESTIVE_SET": "YES" if (h >= suggestive).any() else "NO",
        })
    return pd.DataFrame(rows).sort_values("MAX_H4", ascending=False, na_position="last")


